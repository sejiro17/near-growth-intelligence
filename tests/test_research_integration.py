"""Saved-input rebuild, publication boundaries and headless dashboard smoke tests."""

import importlib.util
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from streamlit.testing.v1 import AppTest


ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("rebuild", ROOT / "analysis/23_rebuild_published_results.py")
m = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(m)


class ResearchIntegrationTests(unittest.TestCase):
    def test_all_published_outputs_reproduce_without_network_or_changes(self):
        files = [p for p in (ROOT / 'results').rglob('*') if p.is_file()]
        before = {p: p.read_bytes() for p in files}
        with patch('socket.socket.connect', side_effect=AssertionError('Network forbidden')):
            report = m.rebuild(check=True)
        self.assertEqual(report['derived_artifacts_verified'], 17)
        self.assertEqual(report['created'], [])
        self.assertEqual(report['source_requests'], 0)
        self.assertTrue(all(p.read_bytes() == raw for p, raw in before.items()))

    def test_generated_mismatch_is_rejected_without_overwrite(self):
        file = m.RESULTS / m.LEGACY[0][1]
        original = file.read_bytes()
        # Substitute generated bytes in memory; never mutate the actual evidence.
        with patch.object(m, 'legacy_outputs', return_value={file: b'changed'}), self.assertRaisesRegex(ValueError, 'Generated-file mismatch'):
            m.rebuild(check=True)
        self.assertEqual(file.read_bytes(), original)

    def test_manifest_nulls_cohort_coverage_and_thesis_tables(self):
        data = json.loads(m.PUBLISHED.read_bytes())
        self.assertTrue(all(value is None for value in data['unavailable'].values()))
        self.assertEqual(sum(p['measurement_available'] for p in data['checkpoints']), 9)
        self.assertEqual(sum(not p['measurement_available'] for p in data['checkpoints']), 3)
        self.assertEqual(data['supply']['canonical_comparison']['additional_validator_updates'], 231)
        self.assertEqual(data['supply']['period']['residual_near'], '16599.51437846169')
        self.assertIsNone(data['withdrawal']['revenue_origin'])
        thesis = (ROOT / 'notes/investment_thesis.md').read_text()
        for question in ('What grew?', 'How much persisted?', 'What executed successfully?',
                         'What economic demand or value capture is demonstrated?'):
            self.assertIn(question, thesis)
        for group in data['shared_week']['populations']:
            self.assertIn(f"{group['observed']['transactions']:,}", thesis)
        self.assertIn('3,871,009', thesis)
        self.assertIn('python3 -B analysis/23_rebuild_published_results.py', (ROOT / 'README.md').read_text())

    def test_dashboard_opening_metrics_and_account_interaction(self):
        with patch('socket.socket.connect', side_effect=AssertionError('Network forbidden')):
            app = AppTest.from_file(str(ROOT / 'dashboard/app.py'), default_timeout=30).run()
            self.assertFalse(app.exception)
            self.assertFalse(app.error)
            text = '\n'.join(x.value for x in app.markdown)
            for question in ('What grew?', 'How much persisted?', 'What executed successfully?',
                             'What economic demand or value capture is demonstrated?'):
                self.assertIn(question, text)
            metrics = {item.label: item.value for item in app.metric}
            self.assertEqual(metrics['Supply minus raw validator change'], '16,599.51437846 NEAR')
            table = next(x.value for x in app.dataframe if 'All +1/+4/+8' in x.value.columns)
            self.assertEqual(table['+8 return'].tolist(), ['47.41%', '46.18%', 'Unavailable', 'Unavailable'])
            app.selectbox(key='explorer_account').select('meteor-relayer.near').run()
            self.assertFalse(app.exception)
            app.selectbox(key='explorer_week').set_value('2026-10-12').run()
            self.assertFalse(app.exception)
            self.assertFalse(app.error)

    def test_dashboard_rejects_changed_source_instead_of_fetching(self):
        from dashboard import research_views as view
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            results = root/'results'
            results.mkdir()
            source = results/'source.json'
            source.write_bytes(b'changed')
            artifact = results/'artifact.json'
            artifact.write_text(json.dumps({'schema_version': 1, 'measurement_phase': 'CLOSED_WITH_STATED_LIMITATIONS',
                'sources': {'results/source.json': {'bytes': 7, 'sha256': '0'*64}}, 'unavailable': {'revenue': None}}))
            view.load_evidence.clear()
            with patch.object(view, 'ROOT', root), patch.object(view, 'ARTIFACT', artifact), self.assertRaisesRegex(ValueError, 'Saved evidence changed'):
                view.load_evidence(view.signature())
            view.load_evidence.clear()


if __name__ == '__main__':
    unittest.main()
